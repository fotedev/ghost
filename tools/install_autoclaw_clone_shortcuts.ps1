#requires -Version 5.1
<#
.SYNOPSIS
  Installs (or removes) Desktop + Start Menu shortcuts for the AutoClaw CLONE
  instances (inst1 / inst2 / inst3 / inst4). Default: all four.

.DESCRIPTION
  A Windows .lnk cannot set environment variables, and each clone AutoClaw
  instance is fully driven by env vars (USERPROFILE / HOME / TEMP / TMPDIR /
  AUTOCLAW_GATEWAY_PORT) plus its --user-data-dir. So each shortcut points at
  src\windows\launch_autoclaw_clone.ps1 with -Instance <name>, which sets the
  isolation env and launches AutoClaw detached (cmd /c start) - any future
  launcher fix automatically applies to the shortcuts.

  Per-clone icons: each shortcut's IconLocation points at its branding dir
  (tools\autoclaw-<color>-branding\tray_icon.ico, generated by
  tools\make_clone_icon.ps1). Missing branding files fall back to the
  AutoClaw.exe icon - never a set-but-absent icon path. The PRIMARY
  AutoClaw.lnk always keeps the stock exe icon (see -RepairPrimaryAumid).

  Per-user locations only -> NO admin rights needed:
    Desktop    : [Environment]::GetFolderPath('Desktop')
    Start Menu : %APPDATA%\Microsoft\Windows\Start Menu\Programs

  Every write is re-read and compared (no silent-success). Unless -SkipAumid is
  given, each shortcut gets System.AppUserModel.ID = <base AUMID>.<instN>
  (base com.zhipuai.autoclaw, set unconditionally by the app itself - verified
  in the installed app.asar, spec section 5.8; read from the Primary .lnk when
  one exists, constant otherwise). NOTE: v1 known limitation - running windows
  all declare the BASE AUMID (no env override exists yet), so shortcuts get
  distinct pins but the running windows share one taskbar button until the v2
  AUMID-suffix patch lands (spec section 7.3c).

  The same repair path (-RepairPrimaryAumid) also strips an ".instN" suffix
  hijacked onto the PRIMARY AutoClaw.lnk AND restores the Primary shortcut's
  wiped icon back to <AutoClaw.exe>,0 (a pin rewrite can empty the icon field -
  same hazard as the ZCode Primary, verified 2026-09-28 there).

  Diagnostic rule (ZCode lesson, do not regress): read .lnk AUMIDs ONLY via
  Shell.Application ExtendedProperty('System.AppUserModel.ID') - decoding the
  whole .lnk as UTF-16 and regexing misaligns on odd byte offsets and reports
  false <none>.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File tools\install_autoclaw_clone_shortcuts.ps1
  powershell -NoProfile -ExecutionPolicy Bypass -File tools\install_autoclaw_clone_shortcuts.ps1 -Instance inst2
  powershell -NoProfile -ExecutionPolicy Bypass -File tools\install_autoclaw_clone_shortcuts.ps1 -Remove
  powershell -NoProfile -ExecutionPolicy Bypass -File tools\install_autoclaw_clone_shortcuts.ps1 -RepairPrimaryAumid
#>
[CmdletBinding()]
param(
  [ValidateSet('inst1', 'inst2', 'inst3', 'inst4')]
  [string[]]$Instance = @('inst1', 'inst2', 'inst3', 'inst4'),
  [switch]$Remove,
  [switch]$DesktopOnly,
  [switch]$StartMenuOnly,
  [switch]$SkipAumid,
  [switch]$RepairPrimaryAumid
)

$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path -Parent $PSScriptRoot
$Launcher = Join-Path $RepoRoot 'src\windows\launch_autoclaw_clone.ps1'

# Must stay in sync with the InstanceMap in launch_autoclaw_clone.ps1.
# BrandingRepo dirs hold tray_icon.ico generated by tools\make_clone_icon.ps1
# (developer-supplied renders 2026-10-17; red is a derived hue-rotate of blue).
$InstanceDefs = @{
  'inst1' = @{ ShortcutName = 'AutoClaw inst1.lnk'; BrandingRepo = 'autoclaw-blue-branding';   DisplayName = 'Blue' }
  'inst2' = @{ ShortcutName = 'AutoClaw inst2.lnk'; BrandingRepo = 'autoclaw-yellow-branding'; DisplayName = 'Yellow' }
  'inst3' = @{ ShortcutName = 'AutoClaw inst3.lnk'; BrandingRepo = 'autoclaw-green-branding';  DisplayName = 'Green' }
  'inst4' = @{ ShortcutName = 'AutoClaw inst4.lnk'; BrandingRepo = 'autoclaw-red-branding';    DisplayName = 'Red' }
}
$BaseAumidConstant = 'com.zhipuai.autoclaw'
$script:Failed = $false

if ($DesktopOnly -and $StartMenuOnly) { $DesktopOnly = $false; $StartMenuOnly = $false }

function Get-ShortcutTargets {
  param([string]$ShortcutName)
  $targets = @()
  if (-not $StartMenuOnly) {
    $targets += Join-Path ([Environment]::GetFolderPath('Desktop')) $ShortcutName
  }
  if (-not $DesktopOnly) {
    $targets += Join-Path $env:APPDATA "Microsoft\Windows\Start Menu\Programs\$ShortcutName"
  }
  return $targets
}

function Assert-Value {
  param([string]$Name, [string]$Expected, [string]$Actual)
  if ($Actual -ieq $Expected) {
    Write-Host "      [ok] $Name" -ForegroundColor Green
  } else {
    Write-Host "      [FAILED] $Name : expected '$Expected' but read '$Actual'" -ForegroundColor Red
    $script:Failed = $true
  }
}

function Add-AumidType {
  if ('ShortcutAumid' -as [type]) { return }
  $cs = @'
using System;
using System.Runtime.InteropServices;

public static class ShortcutAumid
{
    [ComImport, Guid("00021401-0000-0000-C000-000000000046")]
    private class ShellLinkCom { }

    [ComImport, InterfaceType(ComInterfaceType.InterfaceIsIUnknown), Guid("0000010B-0000-0000-C000-000000000046")]
    private interface IPersistFile
    {
        void GetClassID(out Guid pClassID);
        [PreserveSig] int IsDirty();
        void Load([MarshalAs(UnmanagedType.LPWStr)] string pszFileName, uint dwMode);
        void Save([MarshalAs(UnmanagedType.LPWStr)] string pszFileName, bool fRemember);
        void SaveCompleted([MarshalAs(UnmanagedType.LPWStr)] string pszFileName);
        void GetCurFile([MarshalAs(UnmanagedType.LPWStr)] out string ppszFileName);
    }

    [StructLayout(LayoutKind.Sequential, Pack = 4)]
    private struct PROPERTYKEY { public Guid fmtid; public uint pid; }

    [ComImport, InterfaceType(ComInterfaceType.InterfaceIsIUnknown), Guid("886D8EEB-8CF2-4446-8D02-CDBA1DBDCF99")]
    private interface IPropertyStore
    {
        [PreserveSig] int GetCount(out uint cProps);
        [PreserveSig] int GetAt(uint iProp, out PROPERTYKEY pkey);
        [PreserveSig] int GetValue(ref PROPERTYKEY key, out PROPVARIANT pv);
        [PreserveSig] int SetValue(ref PROPERTYKEY key, ref PROPVARIANT pv);
        [PreserveSig] int Commit();
    }

    [StructLayout(LayoutKind.Explicit, Size = 24)] // native x64 PROPVARIANT is 24 bytes
    private struct PROPVARIANT
    {
        [FieldOffset(0)] public ushort vt;
        [FieldOffset(8)] public IntPtr ptr;
    }

    private const ushort VT_LPWSTR = 31;
    private static PROPERTYKEY AppIdKey()
    {
        PROPERTYKEY k;
        k.fmtid = new Guid("9F4C2855-9F79-4B39-A8D0-E1D42DE1D5F3");
        k.pid = 5;
        return k;
    }

    public static void Set(string lnkPath, string aumid)
    {
        IPersistFile pf = (IPersistFile)new ShellLinkCom();
        pf.Load(lnkPath, 2); // STGM_READWRITE
        IPropertyStore ps = (IPropertyStore)pf;
        PROPERTYKEY key = AppIdKey();
        PROPVARIANT pv = new PROPVARIANT();
        pv.vt = VT_LPWSTR;
        pv.ptr = Marshal.StringToCoTaskMemUni(aumid);
        int hr = ps.SetValue(ref key, ref pv);
        Marshal.FreeCoTaskMem(pv.ptr);
        if (hr != 0) Marshal.ThrowExceptionForHR(hr);
        hr = ps.Commit();
        if (hr != 0) Marshal.ThrowExceptionForHR(hr);
        pf.Save(lnkPath, true);
    }
}
'@
  Add-Type -TypeDefinition $cs
}

function Get-LnkAumid {
  # Shell property system ONLY (see header diagnostic rule).
  param([string]$Path)
  $sh = New-Object -ComObject Shell.Application
  $ns = $sh.Namespace((Split-Path -Parent $Path))
  if (-not $ns) { return $null }
  $item = $ns.ParseName((Split-Path -Leaf $Path))
  if (-not $item) { return $null }
  $v = $item.ExtendedProperty('System.AppUserModel.ID')
  if ($null -eq $v) { return $null }
  return ([string]$v)
}

function Get-PrimaryLnkPaths {
  return @(
    (Join-Path ([Environment]::GetFolderPath('Desktop')) 'AutoClaw.lnk'),
    (Join-Path $env:APPDATA 'Microsoft\Windows\Start Menu\Programs\AutoClaw.lnk'),
    (Join-Path $env:ProgramData 'Microsoft\Windows\Start Menu\Programs\AutoClaw.lnk')
  )
}

function Get-AutoClawExe {
  $cands = @(
    'C:\Program Files\AutoClaw\AutoClaw.exe',
    'C:\Program Files (x86)\AutoClaw\AutoClaw.exe',
    (Join-Path $env:LOCALAPPDATA 'Programs\AutoClaw\AutoClaw.exe')
  )
  foreach ($c in $cands) { if (Test-Path -LiteralPath $c) { return $c } }
  return $null
}

function Repair-PrimaryLnkIcon {
  param([string]$Path)
  $ws = New-Object -ComObject WScript.Shell
  $sc = $ws.CreateShortcut($Path)
  $exe = $sc.TargetPath
  if ([string]::IsNullOrWhiteSpace($exe) -or -not (Test-Path -LiteralPath $exe)) { $exe = Get-AutoClawExe }
  if (-not $exe) {
    Write-Host "  [skip] icon restore on $Path - AutoClaw.exe not found." -ForegroundColor Yellow
    return
  }
  $expected = "$exe,0"
  if ($sc.IconLocation -ieq $expected) { return }
  try {
    $sc.IconLocation = $expected
    $sc.Save()
    $chk = (New-Object -ComObject WScript.Shell).CreateShortcut($Path)
    Assert-Value 'IconLocation' $expected $chk.IconLocation
  } catch {
    Write-Host "  [FAILED] icon restore on $Path : $($_.Exception.Message)" -ForegroundColor Red
    $script:Failed = $true
  }
}

function Repair-PrimaryAumid {
  # Strip any trailing ".instN" clone suffix from the primary shortcut's AUMID
  # (a pin rewrite can stamp it there) and restore a wiped icon field.
  Add-AumidType
  $repaired = 0
  $base = $null
  foreach ($c in (Get-PrimaryLnkPaths)) {
    if (-not (Test-Path -LiteralPath $c)) { continue }
    $id = Get-LnkAumid $c
    if (-not [string]::IsNullOrWhiteSpace($id)) {
      if ($base -eq $null) { $base = $id }
      if ($id -match '\.inst\d+$') {
        $clean = $id -replace '\.inst\d+$', ''
        try {
          [ShortcutAumid]::Set($c, $clean)
          $after = Get-LnkAumid $c
          if ($after -ieq $clean) {
            Write-Host "  [ok] repaired AUMID '$id' -> '$clean' in $c" -ForegroundColor Green
            $repaired++
            if ($base -eq $id) { $base = $clean }
            Repair-PrimaryLnkIcon $c
          } else {
            Write-Host "  [FAILED] AUMID still '$after' after repair in $c" -ForegroundColor Red
            $script:Failed = $true
          }
        } catch {
          Write-Host "  [FAILED] AUMID repair on $c : $($_.Exception.Message)" -ForegroundColor Red
          $script:Failed = $true
        }
        continue
      }
    }
    # Healthy AUMID (or none stamped): still heal a wiped icon field.
    Repair-PrimaryLnkIcon $c
  }
  if ($repaired -eq 0) { Write-Host '  [ok] no clone AUMID collision on the primary shortcut.' -ForegroundColor Green }
  return $base
}

function Get-InstalledAutoClawAumid {
  # Prefer the Primary .lnk's own AUMID; fall back to the verified constant
  # (the app sets com.zhipuai.autoclaw unconditionally - spec section 5.8).
  foreach ($c in (Get-PrimaryLnkPaths)) {
    if (Test-Path -LiteralPath $c) {
      $id = Get-LnkAumid $c
      if (-not [string]::IsNullOrWhiteSpace($id)) { return $id }
    }
  }
  return $BaseAumidConstant
}

if ($RepairPrimaryAumid) {
  Write-Host '[repair] Checking primary AutoClaw.lnk AUMID...'
  Add-AumidType
  [void](Repair-PrimaryAumid)
  if ($script:Failed) { Write-Host 'FAILED - see lines above.' -ForegroundColor Red; exit 1 }
  Write-Host 'SUCCESS - primary shortcut AUMID healthy.' -ForegroundColor Green
  exit 0
}

if (-not (Test-Path -LiteralPath $Launcher)) { throw "Launcher not found: $Launcher" }
# Shortcuts always target the OS-shipped Windows PowerShell 5.1 - the
# launchers are 5.1-first, and $PSHOME points at pwsh's own directory (no
# powershell.exe) when this installer itself runs under PowerShell 7.
$psExe   = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
if (-not (Test-Path -LiteralPath $psExe)) { throw "Windows PowerShell not found: $psExe" }
$workDir = Split-Path -Parent $Launcher

if ($Remove) {
  Write-Host '[1/1] Removing shortcuts...'
  foreach ($inst in $Instance) {
    foreach ($t in (Get-ShortcutTargets -ShortcutName $InstanceDefs[$inst].ShortcutName)) {
      if (Test-Path -LiteralPath $t) {
        Remove-Item -LiteralPath $t -Force
        if (Test-Path -LiteralPath $t) {
          Write-Host "  [FAILED] still exists after delete: $t" -ForegroundColor Red
          $script:Failed = $true
        } else {
          Write-Host "  [ok] removed: $t" -ForegroundColor Green
        }
      } else {
        Write-Host "  [skip] not present: $t"
      }
    }
  }
  if ($script:Failed) { Write-Host 'FAILED - see lines above.' -ForegroundColor Red; exit 1 }
  Write-Host 'SUCCESS - shortcuts removed.' -ForegroundColor Green
  exit 0
}

Write-Host '[1/3] Resolving paths...'
$exe = Get-AutoClawExe
$installed = @{}
foreach ($inst in $Instance) {
  $def = $InstanceDefs[$inst]
  $iconOk = $false
  $iconLocation = $null
  # per-clone branding icon first; the AutoClaw.exe icon is the fallback when the
  # branding dir has not been generated yet (never a set-but-absent icon path).
  $iconIco = Join-Path $RepoRoot "tools\$($def.BrandingRepo)\tray_icon.ico"
  if (Test-Path -LiteralPath $iconIco) {
    $iconOk = $true
    $iconLocation = "$iconIco,0"
  } elseif ($exe) {
    $iconOk = $true
    $iconLocation = "$exe,0"
    Write-Host "  [warn] $($def.DisplayName) icon not found: $iconIco - '$($def.ShortcutName)' falls back to the AutoClaw.exe icon (generate with tools\make_clone_icon.ps1)." -ForegroundColor Yellow
  } else {
    Write-Host "  [warn] no $($def.DisplayName) icon and AutoClaw.exe not found - '$($def.ShortcutName)' will use the default icon." -ForegroundColor Yellow
  }
  $installed[$inst] = @{
    Def          = $def
    IconOk       = $iconOk
    IconLocation = $iconLocation
    Description  = "Launch an independent AutoClaw $inst clone (own profile, identity, gateway port - $($def.DisplayName.ToLowerInvariant()) icon)"
    Arguments    = "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$Launcher`" -Instance $inst"
    Targets      = @(Get-ShortcutTargets -ShortcutName $def.ShortcutName)
  }
}

Write-Host '[2/3] Creating shortcuts (verify-after)...'
$ws = New-Object -ComObject WScript.Shell
foreach ($inst in $Instance) {
  $spec = $installed[$inst]
  Write-Host "  [$inst] $($spec.Def.ShortcutName)"
  foreach ($t in $spec.Targets) {
    Write-Host "    -> $t"
    $sc = $ws.CreateShortcut($t)
    $sc.TargetPath = $psExe
    $sc.Arguments = $spec.Arguments
    $sc.WorkingDirectory = $workDir
    if ($spec.IconOk) { $sc.IconLocation = $spec.IconLocation }
    $sc.Description = $spec.Description
    $sc.Save()
    if (-not (Test-Path -LiteralPath $t)) {
      Write-Host "    [FAILED] .lnk not written: $t" -ForegroundColor Red
      $script:Failed = $true
      continue
    }
    $chk = $ws.CreateShortcut($t)
    Assert-Value 'TargetPath'       $psExe            $chk.TargetPath
    Assert-Value 'Arguments'        $spec.Arguments   $chk.Arguments
    Assert-Value 'WorkingDirectory' $workDir          $chk.WorkingDirectory
    if ($spec.IconOk) { Assert-Value 'IconLocation' $spec.IconLocation $chk.IconLocation }
  }
}

Write-Host '[3/3] Setting AppUserModel.ID for taskbar pin grouping...'
if ($SkipAumid) {
  Write-Host '  [skip] -SkipAumid given.'
} else {
  Add-AumidType
  # self-heal first: a collision (AutoClaw.lnk stamped with a clone suffix)
  # would otherwise poison the base computation below into ...inst1.inst2
  $base = Repair-PrimaryAumid
  if ([string]::IsNullOrWhiteSpace($base)) {
    $base = Get-InstalledAutoClawAumid
  }
  foreach ($inst in $Instance) {
    $spec = $installed[$inst]
    $expected = "$base.$inst"
    Write-Host "  [$inst] base AUMID = $base  ->  shortcut AUMID = $expected"
    foreach ($t in $spec.Targets) {
      if (-not (Test-Path -LiteralPath $t)) { continue }
      try {
        [ShortcutAumid]::Set($t, $expected)
        Assert-Value 'AppUserModel.ID' $expected (Get-LnkAumid $t)
      } catch {
        Write-Host "  [FAILED] AUMID set on $t : $($_.Exception.Message)" -ForegroundColor Red
        $script:Failed = $true
      }
    }
  }
  Write-Host '  [note] v1: RUNNING windows all declare the base AUMID (no env override yet),' -ForegroundColor Yellow
  Write-Host '         so they share one taskbar button; the pins above are still per-clone.' -ForegroundColor Yellow
}

Write-Host '=== Summary ==='
if ($script:Failed) {
  Write-Host 'FAILED - see [FAILED] lines above.' -ForegroundColor Red
  exit 1
}
foreach ($inst in $Instance) {
  foreach ($t in $installed[$inst].Targets) { Write-Host "  installed: $t" -ForegroundColor Green }
}
Write-Host 'SUCCESS - double-click a clone shortcut on the Desktop or find it in the Start menu.' -ForegroundColor Green
Write-Host 'Remove later with: tools\install_autoclaw_clone_shortcuts.ps1 -Remove'
exit 0
